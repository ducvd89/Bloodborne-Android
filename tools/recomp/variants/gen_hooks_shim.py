#!/usr/bin/env python3
"""Hook catalog of the port's own code hooks (gpu/shim/bbport_guest_hooks.cpp), generated from the constants in that file.

    tools/recomp/variants/gen_hooks_shim.py > tools/recomp/variants/hooks-shim.txt
    tools/recomp/variants/gen_hooks_shim.py --check tools/recomp/variants/hooks-shim.txt

These sites use guest_cpu_hook (a GuestHook replaces the instruction(s): it carries them out and sets rip), so each is declared `regs` with the
addresses Handle() can set rip to: the end of the replaced instructions, or (the release check) the branch target. The rules below mirror
Handle(); the script stops when the source has a site it does not know.
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[3] / 'gpu/shim/bbport_guest_hooks.cpp'


def main():
    text = SRC.read_text()
    consts = {m.group(1): int(m.group(2), 16) for m in re.finditer(r'constexpr u64 (\w+) = (0x[0-9a-fA-F]+);', text)}
    code_len = {m.group(1): len(re.findall(r'0x[0-9a-fA-F]{2}', m.group(2)))
                for m in re.finditer(r'constexpr unsigned char (\w+)\[\d+\] = \{([^}]*)\};', text)}
    heap = [int(x, 16) for x in re.search(r'HeapAllocReturns = \{([^}]*)\}', text).group(1).replace(' ', '').split(',') if x]
    memcpy_sites = [int(m.group(1), 16) for m in re.finditer(r'\{(0x[0-9a-f]+), \{0xe8,', text)]
    out = ['# Generated by tools/recomp/variants/gen_hooks_shim.py from gpu/shim/bbport_guest_hooks.cpp: do not edit.',
           '# guest_cpu_hook sites (kind regs): the handler replaces the instruction(s) and sets rip to one of resume=.']
    for site in memcpy_sites:   # call memcpy: LoaderCopy, rip after the call
        out.append(f'hook {site:x} 5 regs resume={site + 5:x}')
    a = consts['AllocReturn']
    out.append(f'hook {a:x} {code_len["AllocReturnCode"]} regs resume={a + code_len["AllocReturnCode"]:x}')
    for site in heap:           # mov rbx, rax after the heap allocation call
        n = code_len['HeapAllocReturnCode']
        out.append(f'hook {site:x} {n} regs resume={site + n:x}')
    c = consts['CollectorEntry']  # push rbp; mov rbp, rsp (the AArch64 build replaces all four bytes)
    out.append(f'hook {c:x} 4 regs resume={c + 4:x}')
    r = consts['ReleaseCheck']    # js 0xbb5fc7: the branch target or the next instruction
    out.append(f'hook {r:x} {code_len["ReleaseCheckCode"]} regs resume={r + code_len["ReleaseCheckCode"]:x},{0xbb5fc7:x}')
    result = '\n'.join(out) + '\n'
    if len(sys.argv) > 2 and sys.argv[1] == '--check':
        if Path(sys.argv[2]).read_text() != result:
            sys.exit(f'{sys.argv[2]} is out of date: rerun tools/recomp/variants/gen_hooks_shim.py')
        return
    sys.stdout.write(result)


if __name__ == '__main__':
    main()
